def adj_feminine(adj: str) -> str:
    if adj.endswith("ый"): return adj[:-2] + "ая"
    if adj.endswith("ий"): return adj[:-2] + "яя"
    if adj.endswith("ой"): return adj[:-2] + "ая"
    return adj

